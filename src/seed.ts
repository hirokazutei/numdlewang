// Seeded PRNG — mulberry32 algorithm
function mulberry32(seed: number) {
  return function () {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function hashString(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export function createRng(dateStr: string) {
  return mulberry32(hashString(dateStr));
}

export function getDateString(date = new Date()): string {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, "0");
  const d = String(date.getDate()).padStart(2, "0");
  return `${y}-${m}-${d}`;
}

export const EPOCH = new Date("2024-01-01").getTime();

export function getPuzzleNumber(date = new Date()): number {
  const today = new Date(date.getFullYear(), date.getMonth(), date.getDate());
  return Math.floor((today.getTime() - EPOCH) / 86400000) + 1;
}
